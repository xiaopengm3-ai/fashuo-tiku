def taxonomy_json():
    out = []
    for si, sub in enumerate(SUBJECTS):
        groups = []
        for gi, (gname, nodes) in enumerate(sub["groups"]):
            group_id = f"{sub['id']}-g{gi + 1}"
            groups.append({
                "id": group_id,
                "name": gname,
                "nodes": [{"id": nid, "name": name, "group": group_id} for nid, name, _ in nodes],
            })
        out.append({
            "id": sub["id"], "name": sub["name"], "short": sub["short"],
            "color": sub["color"], "order": si + 1, "groups": groups,
        })
    return out


def node_keywords():
    out = {}
    for sub in SUBJECTS:
        for _, nodes in sub["groups"]:
            for nid, name, kws in nodes:
                out[nid] = {
                    "subject": sub["id"], "name": name,
                    "keywords": [k.strip() for k in kws.split(",") if k.strip()],
                }
    return out
